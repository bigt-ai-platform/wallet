#!/usr/bin/env node
/**
 * scripts/p2p-engine-key.mjs — generate the P2P settlement engine's identity
 * and the per-region secrets file `deploy/env/.env.p2p.<region>` (gitignored;
 * `region.sh p2p` scps it to the VM and passes it as compose --env-file).
 *
 *   node scripts/p2p-engine-key.mjs              # fresh block on stdout
 *   node scripts/p2p-engine-key.mjs europa       # write deploy/env/.env.p2p.europa
 *   node scripts/p2p-engine-key.mjs europa --force   # overwrite (ROTATES KEYS)
 *
 * One ML-DSA-87 key is the whole identity (docs/p2p.md):
 *   SETTLEMENT_ENGINE_KEY    seed hex — signs the L1-SOCIAL anchor records
 *                            (anchor.ts anchorFromEnv re-derives from it)
 *   SETTLEMENT_ENGINE_DID    did:key of that key — the record signer identity
 *   SETTLEMENT_ENGINE_PUBKEY prefixed public key hex — the 2-of-3 escrow
 *                            participant the wallet co-signs with (server.ts
 *                            escrowFor); empty → escrow swaps refuse to form
 *
 * Rotating the key invalidates anchored-record verification and any in-flight
 * escrow (the 2-of-3 address changes), so treat the file like a prod secret.
 */
import { randomBytes } from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PQKey, Utils } from 'bigtangle-ts';
import { didFromPQKey } from 'did/pq';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const region = args.find((a) => !a.startsWith('-')) || '';
const force = args.includes('--force');

/** Region domain from deploy/region.conf (`REGION_DOMAIN[europa]="eu.wallet.bigt.ai"`). */
function regionDomain(name) {
  if (!name) return '';
  const conf = readFileSync(resolve(ROOT, 'deploy/region.conf'), 'utf8');
  const m = conf.match(new RegExp(`REGION_DOMAIN\\[${name}\\]="([^"]+)"`));
  return m ? m[1] : '';
}

const engineKey = PQKey.createNew();
const engineKeySeed = engineKey.getPrivateKeySeedAsHex();
if (!engineKeySeed) throw new Error('PQKey did not expose a private seed — cannot build SETTLEMENT_ENGINE_KEY');
const engineDid = didFromPQKey(engineKey);
/** Prefixed ML-DSA public key → lets the engine derive the 2-of-3 escrow address. */
const enginePubHex = Utils.HEX.encode(engineKey.getPrefixedPublicKeyBytes());
const engineAddrHex = engineKey.toAddress().toHex();

const domain = regionDomain(region);
const cors = ['', domain, 'wallet.bigt.ai', 'www.wallet.bigt.ai']
  .filter(Boolean)
  .map((d) => `https://${d}`)
  .filter((v, i, a) => a.indexOf(v) === i)
  .join(',');

const block = `# P2P settlement engine secrets — deploy/env/.env.p2p.${region || '<region>'}
# Generated by scripts/p2p-engine-key.mjs. Gitignored; region.sh p2p scps this
# to the VM on every run (deploy/env is rsync-excluded), passed to compose as
# --env-file. chmod 600. Rotating the engine key invalidates anchored-record
# verification AND changes the 2-of-3 escrow address (in-flight swaps strand).

# ── store (engine projection; rebuildable from the L0/L1 seeds) ──
POSTGRES_PASSWORD=${randomBytes(18).toString('hex')}
SETTLEMENT_STORE=pg

# ── engine identity: one ML-DSA-87 key, three views of it ──
SETTLEMENT_ENGINE_KEY=${engineKeySeed}
SETTLEMENT_ENGINE_DID=${engineDid}
SETTLEMENT_ENGINE_PUBKEY=${enginePubHex}
SETTLEMENT_ADMIN_TOKEN=${randomBytes(20).toString('hex')}

# ── chains (external). NEVER leave SETTLEMENT_L0_URL empty in prod: with no
#    L0 client the engine accepts escrow_lock WITHOUT proof (server.ts). The
#    plural vars are comma lists: every candidate is gated on a healthy
#    getChainNumber probe (fail closed), the singular var stays as boot seed.
SETTLEMENT_L0_URLS=https://eu1.bigtangle.org,https://eu2.bigtangle.org,https://eu3.bigtangle.org
SETTLEMENT_L0_URL=https://eu1.bigtangle.org
SETTLEMENT_L1_SOCIAL_URLS=https://socialeu1.bigtangle.org,https://socialeu2.bigtangle.org
SETTLEMENT_L1_SOCIAL_URL=https://socialeu1.bigtangle.org

# ── rails: CNY user-to-user only. No PayPal credentials → paypal stays off;
#    SETTLEMENT_PAYPAL_INSECURE must never be set here (mock payouts). ──
SETTLEMENT_CNY_RAILS=wechat,alipay,bank

# ── escrow settlement closure (docs/p2p.md): a presigned swap settles on its
#    own — release at PAYMENT_VERIFIED, refund at EXPIRED. Poll cadence for a
#    broadcast tx before the next tick retries. 0 = hook off. ──
SETTLEMENT_ESCROW_HOOK_MS=30000
SETTLEMENT_ESCROW_POLL_MS=25000

# CORS is belt-and-braces: the engine already allows any *.bigt.ai origin.
CORS_ORIGIN=${cors}

# Fund this address on L1-SOCIAL with BIG (anchor tx fees), e.g. via
# ../blockchain/helper/prod/prod-social-fund.sh — the anchor fails closed until
# the account holds funds.
# engine address: ${engineAddrHex}
`;

if (region && !force && existsSync(resolve(ROOT, `deploy/env/.env.p2p.${region}`))) {
  console.error(
    `deploy/env/.env.p2p.${region} already exists — pass --force to ROTATE (changes the escrow address)`,
  );
  process.exit(1);
}
if (region) {
  mkdirSync(resolve(ROOT, 'deploy/env'), { recursive: true });
  const file = resolve(ROOT, `deploy/env/.env.p2p.${region}`);
  writeFileSync(file, block, { mode: 0o600 });
  chmodSync(file, 0o600);
  console.log(`wrote ${file} (chmod 600)`);
  console.log(`engine DID: ${engineDid}`);
  console.log(`next: ./deploy/region.sh p2p ${region}`);
} else {
  process.stdout.write(block);
}
